-- Stage 03 approved additive migration: ASP.NET Core Identity and revocable admin sessions.
-- No FreeRADIUS rad* or user-manager table is touched. No default administrator.
CREATE TABLE IF NOT EXISTS "AspNetUsers" (
  "Id" text PRIMARY KEY,
  "UserName" varchar(256),
  "NormalizedUserName" varchar(256),
  "Email" varchar(256),
  "NormalizedEmail" varchar(256),
  "EmailConfirmed" boolean NOT NULL DEFAULT false,
  "PasswordHash" text,
  "SecurityStamp" text,
  "ConcurrencyStamp" text,
  "PhoneNumber" text,
  "PhoneNumberConfirmed" boolean NOT NULL DEFAULT false,
  "TwoFactorEnabled" boolean NOT NULL DEFAULT false,
  "LockoutEnd" timestamptz,
  "LockoutEnabled" boolean NOT NULL DEFAULT true,
  "AccessFailedCount" integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS "UserNameIndex" ON "AspNetUsers" ("NormalizedUserName");
CREATE INDEX IF NOT EXISTS "EmailIndex" ON "AspNetUsers" ("NormalizedEmail");

CREATE TABLE IF NOT EXISTS "AspNetRoles" (
  "Id" text PRIMARY KEY,
  "Name" varchar(256),
  "NormalizedName" varchar(256),
  "ConcurrencyStamp" text
);
CREATE UNIQUE INDEX IF NOT EXISTS "RoleNameIndex" ON "AspNetRoles" ("NormalizedName");

CREATE TABLE IF NOT EXISTS "AspNetUserRoles" (
  "UserId" text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
  "RoleId" text NOT NULL REFERENCES "AspNetRoles"("Id") ON DELETE CASCADE,
  PRIMARY KEY("UserId","RoleId")
);
CREATE INDEX IF NOT EXISTS "IX_AspNetUserRoles_RoleId" ON "AspNetUserRoles" ("RoleId");

CREATE TABLE IF NOT EXISTS "AspNetUserClaims" (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "UserId" text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
  "ClaimType" text,
  "ClaimValue" text
);
CREATE INDEX IF NOT EXISTS "IX_AspNetUserClaims_UserId" ON "AspNetUserClaims" ("UserId");

CREATE TABLE IF NOT EXISTS "AspNetRoleClaims" (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "RoleId" text NOT NULL REFERENCES "AspNetRoles"("Id") ON DELETE CASCADE,
  "ClaimType" text,
  "ClaimValue" text
);
CREATE INDEX IF NOT EXISTS "IX_AspNetRoleClaims_RoleId" ON "AspNetRoleClaims" ("RoleId");

CREATE TABLE IF NOT EXISTS "AspNetUserLogins" (
  "LoginProvider" text NOT NULL,
  "ProviderKey" text NOT NULL,
  "ProviderDisplayName" text,
  "UserId" text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
  PRIMARY KEY("LoginProvider","ProviderKey")
);
CREATE INDEX IF NOT EXISTS "IX_AspNetUserLogins_UserId" ON "AspNetUserLogins" ("UserId");

CREATE TABLE IF NOT EXISTS "AspNetUserTokens" (
  "UserId" text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
  "LoginProvider" text NOT NULL,
  "Name" text NOT NULL,
  "Value" text,
  PRIMARY KEY("UserId","LoginProvider","Name")
);

CREATE TABLE IF NOT EXISTS app_admin_sessions (
  id uuid PRIMARY KEY,
  user_id text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE RESTRICT,
  session_token_hash char(64) NOT NULL UNIQUE CHECK (session_token_hash ~ '^[0-9a-f]{64}$'),
  security_stamp text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  idle_expires_at timestamptz NOT NULL,
  absolute_expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  CHECK (absolute_expires_at > created_at),
  CHECK (idle_expires_at <= absolute_expires_at)
);
CREATE INDEX IF NOT EXISTS idx_admin_sessions_user_active
  ON app_admin_sessions (user_id, revoked_at, absolute_expires_at);

CREATE TABLE IF NOT EXISTS app_admin_audit_events (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_user_id text REFERENCES "AspNetUsers"("Id") ON DELETE RESTRICT,
  action varchar(64) NOT NULL,
  subject_kind varchar(64),
  subject_id varchar(160),
  outcome varchar(16) NOT NULL CHECK (outcome IN ('success','denied','error')),
  occurred_at timestamptz NOT NULL DEFAULT now(),
  correlation_id uuid NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_admin_audit_actor_time
  ON app_admin_audit_events (actor_user_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_admin_audit_time
  ON app_admin_audit_events (occurred_at DESC);

